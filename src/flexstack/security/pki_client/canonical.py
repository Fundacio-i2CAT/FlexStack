"""
Canonical key pair of an ITS-S (ETSI TS 102 941 V2.2.1 clause 6.1.2).

The ITS-S signs its initial enrolment request with the canonical private key
(signer ``self``, clause 6.2.3.2.1); the EA verifies it with the canonical
public key registered for the canonical identifier (``itsId``) before the
first request. An unregistered identifier is refused with ``unknownits``, a
request signed with another key with ``invalidsignature``.

:func:`load_or_create_canonical_key` keeps the key pair in two files:

* ``<path>``: the private key, PKCS#8 PEM, mode 0600, created once (never
  overwritten);
* ``<path minus .pem>.pub.pem``: the public key, SubjectPublicKeyInfo PEM, to
  be registered with the EA (pythonpki: ``ea-tool register --its-id ...
  --public-key ...``).

The canonical identifier may be assigned (manufacturer) or generated by the
ITS-S (clause 6.1.3); :func:`canonical_id` generates a stable one from the
public key: the last 8 octets of SHA-256 over the DER SubjectPublicKeyInfo.

The formats and the identifier are the same in RustFlexstack
(``pki_client::canonical``).
"""

from __future__ import annotations

import hashlib
import os
import pathlib
from dataclasses import dataclass

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


@dataclass(frozen=True)
class CanonicalKey:
    """The canonical key pair: private key PEM (PKCS#8), public key PEM (SPKI)."""

    private_pem: bytes
    public_pem: bytes
    private_path: pathlib.Path
    public_path: pathlib.Path
    created: bool

    @property
    def its_id(self) -> bytes:
        """The canonical identifier generated from the public key (:func:`canonical_id`)."""
        return canonical_id(self.public_pem)

    def registration_command(self, its_id: bytes | None = None) -> str:
        """The pythonpki command that registers this ITS-S with the EA."""
        its_id = self.its_id if its_id is None else its_id
        return f"ea-tool register --its-id {its_id.hex()} --public-key {self.public_path}"


def public_key_path(private_path: str | pathlib.Path) -> pathlib.Path:
    """``canonical_key.pem`` -> ``canonical_key.pub.pem``."""
    path = pathlib.Path(private_path)
    stem = path.name[: -len(".pem")] if path.name.endswith(".pem") else path.name
    return path.with_name(f"{stem}.pub.pem")


def canonical_id(public: bytes) -> bytes:
    """Canonical identifier generated from a public key PEM: the last 8 octets of
    SHA-256 over its DER SubjectPublicKeyInfo."""
    der = serialization.load_pem_public_key(public).public_bytes(
        serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo
    )
    return hashlib.sha256(der).digest()[-8:]


def public_pem(private_pem: bytes) -> bytes:
    """SubjectPublicKeyInfo PEM of a canonical private key PEM (P-256)."""
    key = serialization.load_pem_private_key(private_pem, None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != "secp256r1":
        raise ValueError("the canonical key must be a NIST P-256 private key")
    return key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )


def load_or_create_canonical_key(path: str | pathlib.Path) -> CanonicalKey:
    """The canonical key pair kept at ``path``, created (NIST P-256) when absent."""
    private_path = pathlib.Path(path)
    public_path = public_key_path(private_path)
    created = False
    if not private_path.exists():
        private_path.parent.mkdir(parents=True, exist_ok=True)
        key = ec.generate_private_key(ec.SECP256R1())
        pem = key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
        descriptor = os.open(private_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(pem)
        created = True
    private_pem = private_path.read_bytes()
    public = public_pem(private_pem)
    if not public_path.exists() or public_path.read_bytes() != public:
        public_path.write_bytes(public)
    return CanonicalKey(private_pem, public, private_path, public_path, created)
