"""
CAM special-vehicle containers and Service Specific Permissions
(ETSI TS 103 900 V2.3.1, clauses 6.2.2.2, 7.6 and Annex A), traced to
the TS 102 868-2 test purposes are in test_cam_conformance.py.

Mirrors ``rustflexstack::facilities::ca_basic_service::cam_ssp`` tests.
"""

import unittest
from unittest.mock import MagicMock

from flexstack.btp.service_access_point import BTPDataIndication
from flexstack.facilities.ca_basic_service.cam_coder import CAMCoder
from flexstack.facilities.ca_basic_service.cam_reception_management import (
    CAMReceptionManagement,
)
from flexstack.facilities.ca_basic_service.cam_ssp import (
    ROLE_SPECIAL_CONTAINER,
    permissions_bitmap,
    required_permissions,
    ssp_consistent,
)
from flexstack.facilities.ca_basic_service.cam_transmission_management import (
    CAMTransmissionManagement,
    VehicleData,
)

CODER = CAMCoder()
SIREN = (b"\x00", 2)
CONTAINERS = {
    "publicTransportContainer": {"embarkationStatus": False},
    "specialTransportContainer": {"specialTransportType": (b"\x00", 4), "lightBarSirenInUse": SIREN},
    "dangerousGoodsContainer": {"dangerousGoodsBasic": "explosives1"},
    "roadWorksContainerBasic": {"lightBarSirenInUse": SIREN},
    "rescueContainer": {"lightBarSirenInUse": SIREN},
    "emergencyContainer": {"lightBarSirenInUse": SIREN},
    "safetyCarContainer": {"lightBarSirenInUse": SIREN},
}
ROLE_NAMES = {1: "publicTransport", 2: "specialTransport", 3: "dangerousGoods", 4: "roadWork",
              5: "rescue", 6: "emergency", 7: "safetyCar"}
TPV = {"lat": 41.0, "lon": 2.0, "track": 90.0, "speed": 5.0, "time": "2020-01-01T00:00:00Z"}


def vehicle(role, container=None, content=None, **kwargs):
    special = None
    if container is not None:
        special = (container, content if content is not None else CONTAINERS[container])
    return VehicleData(station_id=1, station_type=5, drive_direction="forward",
                       vehicle_length={"vehicleLengthValue": 50,
                                       "vehicleLengthConfidenceIndication": "unavailable"},
                       vehicle_width=30, vehicle_role=role, special_vehicle_data=special, **kwargs)


def generated_cam(vehicle_data) -> dict:
    """First CAM generated by the CA service, as decoded from the wire."""
    btp_router = MagicMock()
    ctm = CAMTransmissionManagement(btp_router, CODER, vehicle_data, None)
    ctm._generate_and_send_cam(TPV, 1_000_000, condition=1)  # pylint: disable=protected-access
    return CODER.decode(btp_router.btp_data_request.call_args[0][0].data)


def with_special(container, content):
    cam = generated_cam(vehicle(0))
    cam["cam"]["camParameters"]["specialVehicleContainer"] = (container, content)
    return cam


class TestSpecialVehicleContainers(unittest.TestCase):
    """Clause 7.6: the container of the vehicle role is sent."""

    def test_each_role_sends_its_container(self):
        for role, container in ROLE_SPECIAL_CONTAINER.items():
            with self.subTest(role=role):
                params = generated_cam(vehicle(role, container))["cam"]["camParameters"]
                self.assertEqual(params["specialVehicleContainer"][0], container)
                self.assertEqual(params["lowFrequencyContainer"][1]["vehicleRole"],
                                 ROLE_NAMES[role])

    def test_container_of_another_role_is_rejected(self):
        with self.assertRaises(ValueError):
            vehicle(6, "safetyCarContainer")

    def test_container_without_special_role_is_rejected(self):
        with self.assertRaises(ValueError):
            vehicle(0, "emergencyContainer")
        with self.assertRaises(ValueError):
            vehicle(9, "emergencyContainer")       # commercial(9): no special container


class TestCamSsp(unittest.TestCase):
    """TS 103 900 V2.3.1 Table 3."""

    def test_plain_vehicle_needs_no_permission(self):
        self.assertEqual(required_permissions(generated_cam(vehicle(0))), [])
        self.assertTrue(ssp_consistent(bytes([2, 0, 0]), generated_cam(vehicle(0))))

    def test_container_bits_of_octet_1(self):
        bits = {"publicTransportContainer": 0x40, "specialTransportContainer": 0x20,
                "dangerousGoodsContainer": 0x10, "roadWorksContainerBasic": 0x08,
                "rescueContainer": 0x04, "emergencyContainer": 0x02, "safetyCarContainer": 0x01}
        for container, bit in bits.items():
            with self.subTest(container=container):
                cam = with_special(container, CONTAINERS[container])
                self.assertEqual(required_permissions(cam), [(1, bit, 0)])
                self.assertTrue(ssp_consistent(bytes([2, bit, 0]), cam))
                self.assertFalse(ssp_consistent(bytes([2, 0xFF ^ bit, 0xFF]), cam))

    def test_octet_2_detailed_permissions(self):
        closed = with_special("roadWorksContainerBasic",
                              {"lightBarSirenInUse": SIREN, "closedLanes": {}})
        self.assertIn((2, 0x80, 0), required_permissions(closed))
        priority = with_special("emergencyContainer",
                                {"lightBarSirenInUse": SIREN, "emergencyPriority": (b"\xc0", 2)})
        self.assertIn((2, 0x40, 0), required_permissions(priority))
        self.assertIn((2, 0x20, 0), required_permissions(priority))
        safety = with_special("safetyCarContainer",
                              {"lightBarSirenInUse": SIREN, "trafficRule": "noPassing", "speedLimit": 50})
        self.assertIn((2, 0x10, 0), required_permissions(safety))
        self.assertIn((2, 0x04, 0), required_permissions(safety))
        self.assertFalse(ssp_consistent(bytes([2, 0x01, 0x10]), safety))   # speedLimit missing
        self.assertTrue(ssp_consistent(bytes([2, 0x01, 0x14]), safety))
        trucks = with_special("safetyCarContainer",
                              {"lightBarSirenInUse": SIREN, "trafficRule": "noPassingForTrucks"})
        self.assertIn((2, 0x08, 0), required_permissions(trucks))

    def test_rsu_protected_zones_bit(self):
        cam = generated_cam(vehicle(0))
        cam["cam"]["camParameters"]["basicContainer"]["stationType"] = 15
        cam["cam"]["camParameters"]["highFrequencyContainer"] = (
            "rsuContainerHighFrequency", {"protectedCommunicationZonesRSU": []})
        self.assertEqual(required_permissions(cam), [(1, 0x80, 0)])

    def test_two_wheeler_bits_need_ssp_version_3(self):
        cam = generated_cam(vehicle(0))
        cam["cam"]["camParameters"]["extensionContainers"] = [
            {"containerId": 1, "containerData": b""}]
        decode = MagicMock(return_value={"typeSpecificInformation": ("cyclist", {})})
        needed = required_permissions(cam, decode)
        self.assertEqual(needed, [(2, 0x02, 3), (2, 0x01, 3)])
        self.assertTrue(ssp_consistent(bytes([2, 0, 0]), cam, decode))       # not expressible in v2
        self.assertFalse(ssp_consistent(bytes([3, 0, 0x02]), cam, decode))   # cyclist bit missing
        self.assertTrue(ssp_consistent(bytes([3, 0, 0x03]), cam, decode))
        # Sender side (clause 6.2.2.2): the two-wheeler bits are requested.
        self.assertEqual(permissions_bitmap(cam, decode), bytes([0, 0, 0x03]))
        self.assertEqual(permissions_bitmap(cam), bytes([0, 0, 0x02]))

    def test_no_ssp_means_no_check(self):
        cam = with_special("emergencyContainer", CONTAINERS["emergencyContainer"])
        self.assertTrue(ssp_consistent(None, cam))
        self.assertTrue(ssp_consistent(b"", cam))

    def test_test_version_permits_no_protected_content(self):
        cam = with_special("emergencyContainer", CONTAINERS["emergencyContainer"])
        self.assertFalse(ssp_consistent(bytes([0]), cam))


class TestSenderPermissions(unittest.TestCase):
    """Sender-side SSP: the CA service requests the permissions its CAM needs."""

    def test_bitmap_of_protected_content(self):
        self.assertEqual(permissions_bitmap(generated_cam(vehicle(0))), b"\x00")
        emergency = generated_cam(vehicle(6, "emergencyContainer"))
        self.assertEqual(permissions_bitmap(emergency), bytes([0, 0x02, 0]))

    def test_cam_request_carries_the_permissions(self):
        btp_router = MagicMock()
        ctm = CAMTransmissionManagement(btp_router, CODER, vehicle(6, "emergencyContainer"), None)
        ctm._generate_and_send_cam(TPV, 1_000_000, condition=1)  # pylint: disable=protected-access
        request = btp_router.btp_data_request.call_args[0][0]
        self.assertEqual(request.security_permissions, bytes([0, 0x02, 0]))


class TestReceptionSsp(unittest.TestCase):
    """Clause 6.2.2.1: CAM not consistent with the signer's SSP is discarded."""

    def setUp(self):
        self.reception = CAMReceptionManagement(CODER, MagicMock(), None)
        self.callback = MagicMock()
        self.reception.add_application_callback(self.callback)
        cam = generated_cam(vehicle(6, "emergencyContainer"))
        self.data = CODER.encode(cam)

    def test_inconsistent_ssp_discards(self):
        self.reception.reception_callback(
            BTPDataIndication(data=self.data, gn_permissions=bytes([2, 0x01, 0])))
        self.callback.assert_not_called()

    def test_secured_cam_with_another_its_aid_is_discarded(self):
        """ETSI TS 103 097 clause 7.1.1: a secured CAM shall carry the CAM ITS-AID."""
        self.reception.reception_callback(
            BTPDataIndication(data=self.data, gn_permissions=bytes([2, 0x02, 0]), gn_its_aid=37))
        self.callback.assert_not_called()
        self.reception.reception_callback(
            BTPDataIndication(data=self.data, gn_permissions=bytes([2, 0x02, 0]), gn_its_aid=36))
        self.callback.assert_called_once()

    def test_consistent_ssp_accepts(self):
        self.reception.reception_callback(
            BTPDataIndication(data=self.data, gn_permissions=bytes([2, 0x02, 0])))
        self.callback.assert_called_once()


if __name__ == "__main__":
    unittest.main()
